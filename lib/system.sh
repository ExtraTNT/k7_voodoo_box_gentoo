# shellcheck shell=bash
# Target-system functions. Run INSIDE the installed system (stage-1 chroot or
# bootstrap.sh), so paths are absolute ("/etc/...").  Needs lib/common.sh.

# ── Portage ────────────────────────────────────────────────────────────────
render_make_conf() {
  local features="parallel-fetch"
  is_yes "$OFFICIAL_BINHOST" && features+=" getbinpkg"
  cat <<EOF
# GENERATED from install.conf (/etc/system.conf) — edit that, then run bootstrap.sh.
COMMON_FLAGS="$COMMON_FLAGS"
CFLAGS="\${COMMON_FLAGS}"
CXXFLAGS="\${COMMON_FLAGS}"
FCFLAGS="\${COMMON_FLAGS}"
FFLAGS="\${COMMON_FLAGS}"
LDFLAGS="-Wl,-O1 -Wl,--as-needed"
MAKEOPTS="$MAKEOPTS"
EMERGE_DEFAULT_OPTS="--quiet-build=y --keep-going=y"
CPU_FLAGS_X86="$CPU_FLAGS_X86"
USE="$USE_FLAGS"
VIDEO_CARDS="$VIDEO_CARDS"
INPUT_DEVICES="$INPUT_DEVICES"
L10N="$L10N"
GRUB_PLATFORMS="pc"
ACCEPT_LICENSE="$ACCEPT_LICENSE"
GENTOO_MIRRORS="$GENTOO_MIRROR"
FEATURES="$features"
LC_MESSAGES=C.utf8
EOF
}

# Copy the repo's portage/ tree over /etc/portage (additive), then render the
# generated files.  SRC = path of the repo's portage/ directory.
apply_portage_config() {
  local src=$1
  mkdir -p /etc/portage
  cp -rT "$src" /etc/portage
  render_make_conf > /etc/portage/make.conf

  mkdir -p /etc/portage/binrepos.conf
  if ! is_yes "$OFFICIAL_BINHOST"; then
    rm -f /etc/portage/binrepos.conf/gentoobinhost.conf
  fi

  # big builds that do not fit a ${PORTAGE_TMPFS} tmpfs go to disk
  mkdir -p /var/tmp/notmpfs
  chown portage:portage /var/tmp/notmpfs
}

# ── fstab ──────────────────────────────────────────────────────────────────
write_fstab() {
  local root swap
  root=$(blkid -s PARTUUID -o value "$(part 1)")
  {
    echo "# GENERATED by the S2466 installer"
    echo "PARTUUID=$root  /  ext4  $ROOT_MOUNT_OPTS  0 1"
    if [[ $SWAP_SIZE != 0 ]]; then
      swap=$(blkid -s PARTUUID -o value "$(part 2)")
      echo "PARTUUID=$swap  none  swap  sw  0 0"
    fi
    if [[ -n $PORTAGE_TMPFS ]]; then
      echo "tmpfs  /var/tmp/portage  tmpfs  size=$PORTAGE_TMPFS,uid=portage,gid=portage,mode=775,noatime  0 0"
    fi
  } > /etc/fstab
}

# ── kernel ─────────────────────────────────────────────────────────────────
# i386_defconfig + our fragment.  Everything to reach / is built in, so no
# initramfs is needed (= faster boot).
# KERNEL_FRAGMENT may list several files (merged in order, later wins).
kernel_fragments() { # BASEDIR -> one absolute path per line
  local f
  for f in $KERNEL_FRAGMENT; do echo "$1/$f"; done
}

build_kernel() { # FRAGMENT...
  local ver f merged
  for f in "$@"; do [[ -r $f ]] || die "kernel fragment missing: $f"; done
  merged=$(mktemp)
  cat "$@" > "$merged"
  eselect kernel set "$(eselect kernel list | awk '/\[[0-9]+\]/ {n=$1} END {gsub(/[][]/, "", n); print n}')"
  cd /usr/src/linux || die "no /usr/src/linux"
  make -s i386_defconfig
  scripts/kconfig/merge_config.sh -m .config "$@" >/dev/null
  make -s olddefconfig
  check_kernel_config "$merged"
  log "compiling kernel ($MAKEOPTS) — ~30-60 min on the Athlons, minutes on a modern PC"
  # shellcheck disable=SC2086
  make -s $MAKEOPTS bzImage modules
  make -s modules_install
  ver=$(make -s kernelrelease)
  cp arch/x86/boot/bzImage "/boot/vmlinuz-$ver"
  cp System.map "/boot/System.map-$ver"
  cp .config "/boot/config-$ver"
  cd / || true
  mkdir -p /var/lib/autoinstall
  fragments_hash "$merged" > /var/lib/autoinstall/kernel-fragment.sha256
  rm -f "$merged"
  log "kernel $ver installed"
}

# The kernel's identity: sha256 of its merged fragments.
fragments_hash() { cat "$@" | sha256sum | cut -d' ' -f1; }

kernel_fragment_changed() { # FRAGMENT...
  local old=/var/lib/autoinstall/kernel-fragment.sha256
  [[ ! -r $old ]] || [[ $(fragments_hash "$@") != "$(cat "$old")" ]]
}

# Unpack a kernel built by build/prebuild.sh, if one matches the fragments.
install_prebuilt_kernel() { # DIR FRAGMENT...
  local dir=$1 h tb
  shift
  h=$(fragments_hash "$@")
  tb=$dir/linux-$h.tar.xz
  [[ -r $tb ]] || return 1
  log "prebuilt kernel: ${tb##*/}"
  tar xpf "$tb" -C /
  mkdir -p /var/lib/autoinstall
  echo "$h" > /var/lib/autoinstall/kernel-fragment.sha256
}

# Kernel from a prebuilt tarball if possible, else compile it here.
kernel_install_or_build() { # PREBUILT_KERNEL_DIR FRAGMENT...
  local dir=$1
  shift
  install_prebuilt_kernel "$dir" "$@" && return 0
  warn "no prebuilt kernel for these fragments — compiling (~30-60 min on the Athlons)"
  emerge --noreplace "$KERNEL_PKG"
  build_kernel "$@"
}

# Sync the tree to the date the prebuilt packages were built against, so their
# versions match.  Falls back to the latest snapshot.
tree_date() { date -u -d "$(head -n1 /var/db/repos/gentoo/metadata/timestamp.chk 2>/dev/null)" +%Y%m%d 2>/dev/null; }

sync_tree_to() { # SNAPSHOT_FILE (YYYYMMDD of the tree's timestamp)
  local d="" try
  [[ -r $1 ]] && d=$(<"$1")
  if [[ $d =~ ^[0-9]{8}$ ]]; then
    log "portage tree: the one of $d (matches the prebuilt packages)"
    # the mirror names a snapshot after the day BEFORE its timestamp
    # (gentoo-20261113 holds the tree of 20261114 00:45 UTC)
    for try in "$(date -u -d "$d -1 day" +%Y%m%d)" "$d"; do
      if emerge-webrsync -q --revert="$try" >/dev/null 2>&1 && [[ $(tree_date) == "$d" ]]; then
        log "tree $d from snapshot $try"
        return 0
      fi
    done
    log "no snapshot of $d on the mirror (yet) — taking the latest tree"
  fi
  emerge-webrsync -q || warn "emerge-webrsync failed — keeping the current tree"
  if [[ -n $d ]]; then
    local now
    now=$(tree_date)
    if [[ $now == "$d" ]]; then
      log "latest tree is $now — matches the prebuilt packages"
    else
      warn "tree $now, packages built for $d — what differs gets compiled here"
    fi
  fi
}

# Warn about fragment options that olddefconfig silently dropped (missing deps).
check_kernel_config() {
  local fragment=$1 line sym want got bad=0
  declare -A last=()
  # with several fragments only the last setting of a symbol counts
  while IFS= read -r line; do
    if [[ $line =~ ^(CONFIG_[A-Z0-9_]+)= || $line =~ ^#\ (CONFIG_[A-Z0-9_]+)\ is\ not\ set ]]; then
      last[${BASH_REMATCH[1]}]=$line
    fi
  done < "$fragment"
  while IFS= read -r line; do
    if [[ $line =~ ^(CONFIG_[A-Z0-9_]+)=(.*)$ ]]; then
      sym=${BASH_REMATCH[1]} want=${BASH_REMATCH[2]}
    elif [[ $line =~ ^#\ (CONFIG_[A-Z0-9_]+)\ is\ not\ set ]]; then
      sym=${BASH_REMATCH[1]} want=n
    else
      continue
    fi
    got=$(grep -E "^$sym=" .config | cut -d= -f2-) || true
    [[ -z $got ]] && got=n
    if [[ $got != "$want" ]]; then
      warn "kernel: $sym wanted '$want' got '$got'"
      bad=1
    fi
  done < <(printf '%s\n' "${last[@]}")
  ((bad == 0)) && log "kernel config matches fragment"
  return 0
}

# ── bootloader ─────────────────────────────────────────────────────────────
# /etc/default/grub + grub.cfg from install.conf.  Safe to run any time.
grub_config() {
  local style=menu
  ((GRUB_TIMEOUT == 0)) && style=hidden
  cat > /etc/default/grub <<EOF
# GENERATED from install.conf
GRUB_DISTRIBUTOR="Gentoo"
GRUB_TIMEOUT=$GRUB_TIMEOUT
GRUB_TIMEOUT_STYLE=$style
GRUB_CMDLINE_LINUX_DEFAULT="$KERNEL_CMDLINE"
# no initramfs -> the kernel cannot resolve UUID=, but it can PARTUUID=
GRUB_DISABLE_LINUX_UUID=true
GRUB_DISABLE_LINUX_PARTUUID=false
GRUB_DISABLE_RECOVERY=true
GRUB_DISABLE_OS_PROBER=true
GRUB_TERMINAL=console
GRUB_GFXPAYLOAD_LINUX=text
EOF
  grub-mkconfig -o /boot/grub/grub.cfg 2>/dev/null
}

install_grub() {
  grub-install --target=i386-pc "$DISK"
  grub_config
}

# ── boot screen ("splash") ─────────────────────────────────────────────────
# A POST-style text screen instead of boot chatter: the kernel is quiet,
# OpenRC's normal output goes to its log (/var/log/rc.log) — its warnings and
# errors (stderr) still reach the screen — and early in the boot runlevel
# s2466-post clears the screen and lists what was found (cpus, ram, disks,
# gpus, sound, net) plus the kernel's warnings and errors.
setup_splash() { # POST_DIR (repo's post/)
  local inittab_re='^(si|rc|l[2-5]):'
  if ! is_yes "$SPLASH"; then
    rc-update del s2466-post boot >/dev/null 2>&1 || true
    rm -f /etc/init.d/s2466-post /usr/local/sbin/s2466-post
    sed -i -E "/$inittab_re/ s| >/dev/null\$||" /etc/inittab
    return 0
  fi
  install -m 755 "$1/s2466-post" /usr/local/sbin/s2466-post
  install -m 755 "$1/s2466-post.initd" /etc/init.d/s2466-post
  rc-update add s2466-post boot >/dev/null
  # stdout of the boot to /dev/null (rc_logger keeps it), stderr stays
  sed -i -E "/$inittab_re/ { / >\/dev\/null\$/! s|\$| >/dev/null| }" /etc/inittab
  sed -i 's/^#\?rc_logger=.*/rc_logger="YES"/' /etc/rc.conf
}
